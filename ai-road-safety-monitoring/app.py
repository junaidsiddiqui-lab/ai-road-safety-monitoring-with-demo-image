"""Streamlit interface for the AI-Based Road Safety Monitoring System.
It only DISPLAYS results already generated by `python main.py all`; it never invents results.
Run:  streamlit run app.py"""
import joblib
import numpy as np
import pandas as pd
import streamlit as st
import config
from src import data_loader as dl

st.set_page_config(page_title="Road Safety Monitoring", page_icon="🚦", layout="wide")
PAGES = ["1. Project Overview", "2. Accident Data & Cleaning", "3. Exploratory Data Analysis", "4. Image Processing",
         "5. Feature Detection & Matching", "6. Model Comparison", "7. Evaluation & Limitations"]
page = st.sidebar.radio("Navigate", PAGES)
st.sidebar.caption(f"{config.STUDENT_NAME} | {config.ROLL_NUMBER}\n\n{config.UNIVERSITY}")
MISSING = "Results not found. Add the datasets (see data/README.md) and run `python main.py all`."


def show_img(path, caption=None):
    if path.exists():
        st.image(str(path), caption=caption or path.name, use_container_width=True)
    else:
        st.info(f"Missing file: {path.name}")


clean = dl.read_json(config.CLEANING_SUMMARY)
eda = dl.read_json(config.EDA_FINDINGS)
feat = dl.read_json(config.METRICS_DIR / "feature_matching.json")
proc = dl.read_json(config.METRICS_DIR / "image_processing.json")
cls = dl.read_json(config.METRICS_DIR / "image_classification.json")
mod = dl.read_json(config.METRICS_DIR / "accident_models_summary.json")
table_path = config.METRICS_DIR / "accident_model_comparison.csv"

st.title(config.PROJECT_TITLE)

if page == PAGES[0]:
    st.markdown("""
This educational system has **two connected components** with one road-safety goal:
* **A. Accident analytics** - clean real accident records, explore patterns, and train models that estimate whether an accident was *fatal/serious* or *slight*.
* **B. Road image analysis** - classical computer vision (grayscale, Gaussian blur, CLAHE, Canny, ORB features, matching, Bag-of-Visual-Words classification).

The two components use **separate datasets**; no image is linked to any accident record. This application does **not** detect helmet violations or analyse live video.
""")
    st.subheader("Pipeline status")
    st.json(dl.read_json(config.STATUS_FILE, {"info": MISSING}))
    st.markdown("Dataset names, links and licences: see `LICENSE_AND_DATA_SOURCES.md`.")

elif page == PAGES[1]:
    st.header("Accident dataset and data cleaning")
    if not clean:
        st.warning(MISSING)
    else:
        a, b, c = st.columns(3)
        a.metric("Raw rows", f"{clean['raw']['rows']:,}"); b.metric("Clean rows", f"{clean['clean']['rows']:,}")
        c.metric("Severe share (target=1)", f"{clean['severe_share']:.1%}")
        st.subheader("Cleaning decisions")
        st.dataframe(pd.DataFrame(clean["steps"])[["problem", "method", "why"]], use_container_width=True)
        ft = clean.get("feature_types", {})
        if ft:
            st.subheader("Feature types"); st.json({k: v for k, v in ft.items() if k != "excluded"})
            st.subheader("Excluded columns (leakage / identifiers)"); st.json(ft.get("excluded", {}))
        if config.CLEAN_FILE.exists():
            st.subheader("Cleaned data preview"); st.dataframe(pd.read_csv(config.CLEAN_FILE, nrows=100), use_container_width=True)

elif page == PAGES[2]:
    st.header("Exploratory data analysis")
    if not eda:
        st.warning(MISSING)
    else:
        st.subheader("Findings (computed from the data)")
        for f in eda["findings"]:
            st.markdown(f"- {f}")
        st.caption("Associations are observational and do not prove causation.")
        for k, name in eda["figures"].items():
            show_img(config.FIG_DIR / name)

elif page == PAGES[3]:
    st.header("Basic image processing")
    if not proc:
        st.warning(MISSING)
    else:
        st.dataframe(pd.DataFrame(proc["images"]).drop(columns=["comparison_figure"]), use_container_width=True)
        for p in proc["images"]:
            show_img(config.FIG_DIR / p["comparison_figure"])
        st.markdown("**Why:** grayscale removes colour so features depend on structure; Gaussian blur suppresses noise; CLAHE boosts local contrast in dark/hazy scenes.")

elif page == PAGES[4]:
    st.header("Feature detection and matching")
    if not feat:
        st.warning(MISSING)
    else:
        if feat.get("warning"):
            st.warning(feat["warning"])
        st.dataframe(pd.DataFrame(feat["per_image"]), use_container_width=True)
        c1, c2 = st.columns(2)
        for col, m in zip((c1, c2), ("crosscheck", "ratio")):
            col.metric(f"{m} matches", feat[m]["matches"], f"{feat[m]['ransac_inliers']} RANSAC inliers")
        show_img(config.FIG_DIR / "edges_and_keypoints.png")
        for m in ("ratio", "crosscheck"):
            show_img(config.MATCH_DIR / feat[m]["figure"], f"BFMatcher (Hamming), {m}")
        st.subheader("Image classification (ORB BoVW)")
        if cls and cls.get("status") == "done":
            st.dataframe(pd.DataFrame({n: {k: v for k, v in m.items() if k in ("accuracy", "precision_macro", "recall_macro", "f1_macro")} for n, m in cls["models"].items()}).T)
            for f in sorted(config.FIG_DIR.glob("img_cm_*.png")):
                show_img(f)
        elif cls:
            st.info(f"Classification skipped: {cls.get('reason')}")
        else:
            st.info("Image classification has not been run.")

elif page == PAGES[5]:
    st.header("Accident severity model comparison")
    if not mod or not table_path.exists():
        st.warning(MISSING)
    else:
        st.markdown(f"**Task:** {mod['target']}. **Primary metric:** {mod['primary_metric']}. Majority-class baseline accuracy: {mod['majority_class_baseline_accuracy']:.3f}")
        st.dataframe(pd.read_csv(table_path).style.format(precision=3), use_container_width=True)
        st.success(f"Best model: {mod['best_model']}"); st.write(mod["justification"])
        show_img(config.FIG_DIR / "model_comparison.png"); show_img(config.FIG_DIR / "rf_feature_importance.png")
        cm_cols = st.columns(2)
        for i, f in enumerate(sorted(config.FIG_DIR.glob("cm_*.png"))):
            with cm_cols[i % 2]:
                show_img(f)

        st.subheader("Try the best model (educational demo)")
        schema = dl.read_json(config.SCHEMA_FILE)
        if schema and config.MODEL_FILE.exists():
            model = joblib.load(config.MODEL_FILE)
            num, cat = schema["numeric"], schema["categorical"]
            c1, c2, c3 = st.columns(3)
            hour = c1.slider("Hour of day", 0, 23, 12)
            month = c2.slider("Month", 1, 12, 6)
            weekday = c3.selectbox("Weekday", ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"])
            wd = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"].index(weekday)
            row = {"hour_sin": np.sin(2 * np.pi * hour / 24), "hour_cos": np.cos(2 * np.pi * hour / 24), "month": month,
                   "is_weekend": float(wd >= 5), "is_rush_hour": float(hour in (7, 8, 9, 16, 17, 18)),
                   "is_night": float(hour < 6 or hour >= 21), "day_of_week": str(wd)}
            for i, (c, s) in enumerate(num.items()):
                if c in row:
                    continue
                lo, hi, med = s["min"], s["max"], s["median"]
                row[c] = st.number_input(c, min_value=lo, max_value=hi, value=min(max(med, lo), hi))
            for c, vals in cat.items():
                if c in row:
                    continue
                choice = st.selectbox(f"{c} (code)", vals + ["Unknown"])
                row[c] = np.nan if choice == "Unknown" else choice
            if st.button("Estimate"):
                X = pd.DataFrame([row])[schema["feature_order"]]
                try:
                    p = model.predict_proba(X)[0, 1]
                    st.metric("Model score: probability of Fatal/Serious", f"{p:.1%}")
                except Exception:
                    st.metric("Predicted class", "Fatal/Serious" if model.predict(X)[0] == 1 else "Slight")
                st.warning("Educational demo only. Trained on observational records; class weighting inflates probabilities, so the score is not a calibrated risk. It must not be used for real safety decisions.")
        else:
            st.info("No trained model found.")

else:
    st.header("Evaluation results and limitations")
    if mod:
        st.write("Training vs test performance (F1 of Fatal/Serious class):")
        t = pd.read_csv(table_path)[["model", "train_f1", "test_f1", "f1_gap_train_minus_test", "fit_diagnosis"]]
        st.dataframe(t.style.format(precision=3), use_container_width=True)
    else:
        st.warning(MISSING)
    rep = config.REPORT_DIR / "final_report.md"
    if rep.exists():
        with st.expander("Final report (markdown)"):
            st.markdown(rep.read_text().replace("../figures/", "outputs/figures/"))
    st.subheader("Limitations")
    st.markdown("""
* Accident data are observational: associations are **not** causes.
* Models are educational; they do not guarantee or measure real road safety.
* Slight accidents are under-reported; codes and regions limit generalisation.
* Classical ORB features are sensitive to viewpoint, lighting and blur; ratio-test matches can still be wrong.
* No helmet-violation or live-video detection is implemented.
""")
